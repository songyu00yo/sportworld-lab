#!/usr/bin/env python3
"""Initialize local files, optionally install the pinned official Android SDK."""
import argparse
import os
from pathlib import Path
import platform
import shlex
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
SEEDS = {
    "stadium-route.json": "routes/neusoft-track-route.json",
    "elevation-reference.json": "reference/user-elevation-profile.json",
}


def write_local(path, data, *, mode=0o600, preserve=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".bootstrap-", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        temporary.chmod(mode)
        if preserve:
            try:
                os.link(temporary, path)
            except FileExistsError:
                pass
        else:
            os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def initialize(root=ROOT):
    root = Path(root).resolve()
    lab = root / ".lab"
    lab.mkdir(parents=True, exist_ok=True)
    for private in (root / "private", root / "private/runs", lab / "private"):
        private.mkdir(mode=0o700, parents=True, exist_ok=True)
        private.chmod(0o700)
    for example, relative in SEEDS.items():
        destination = lab / relative
        if not destination.exists():
            write_local(destination, (root / "examples" / example).read_bytes(), preserve=True)
    android = lab / "android"
    for name in ("sdk", "downloads", "user", "emulator-home", "avd", "logs", "xdg-config", "xdg-cache", "xdg-data"):
        (android / name).mkdir(parents=True, exist_ok=True)
    variables = {
        "ANDROID_LAB_ROOT": android,
        "ANDROID_HOME": android / "sdk",
        "ANDROID_SDK_ROOT": android / "sdk",
        "ANDROID_USER_HOME": android / "user",
        "ANDROID_EMULATOR_HOME": android / "emulator-home",
        "ANDROID_AVD_HOME": android / "avd",
        "ANDROID_ADB_SERVER_PORT": "15037",
        "ADB_SERVER_SOCKET": "tcp:localhost:15037",
    }
    environment = "# Generated by scripts/bootstrap.py\n" + "".join(
        f"export {name}={shlex.quote(str(value))}\n" for name, value in variables.items())
    write_local(lab / "android-env.sh", environment.encode("utf-8"))
    wrapper = lab / "start_android_tablet.sh"
    wrapper_text = ('#!/bin/sh\nset -eu\nSPORTWORLD_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)\n'
                       'exec /bin/sh "$SPORTWORLD_ROOT/scripts/start_android_tablet.sh" "$@"\n')
    write_local(wrapper, wrapper_text.encode("utf-8"), mode=0o755)
    return lab


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--offline", action="store_true", help="Initialize local examples without network or device access")
    mode.add_argument("--android", action="store_true", help="Download the official pinned SDK and create an unstarted AVD")
    args = parser.parse_args()
    if args.android and (sys.platform != "darwin" or platform.machine() != "arm64"):
        parser.exit(1, "The pinned Android environment requires macOS on Apple Silicon.\n")
    try:
        lab = initialize()
        if args.android:
            from setup_android import install
            install()
            subprocess.run(["/bin/sh", str(ROOT / "scripts/create_android_avd.sh")], check=True, cwd=ROOT)
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        parser.exit(1, str(error) + "\n")
    print(f"Local files ready in {lab}")


if __name__ == "__main__":
    main()
